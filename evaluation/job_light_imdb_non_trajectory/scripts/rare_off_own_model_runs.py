#!/usr/bin/env python3
"""Run bookkeeping for the rare-support-off own-model main rows (decided 2026-11-25).

The main rows follow the preregistered rule (step 11,000, training seeds 0-2) on
the runs trained by model/slurm/job_light_main_rare_off.sbatch. Three helpers for
the Slurm chain in slurm/submit_rare_off_own_model_tables.sh, run from the
repository root:

  final-config --workload W --seed S
      Write the final-checkpoint sensitivity config of one seed and print its path.
      The final step is the highest checkpoint_step_<N>.pt of the finished run (the
      runs stop early at different steps), so it is resolved when the job starts.
  timing-plans --run-id R --output-directory D
      Write the CPU and GPU timing plans of the six rule runs (both workloads,
      seeds 0-2) completed under run id R.
  sensitivity-args --rule-run-id R --final-run-id F
      Print the arguments of aggregate_own_model_sensitivity.py for these runs.

A run directory is results/joblight_phase1/own_model/<variant>/seed_<S>/<run id>-<hash>;
every lookup must find exactly one completed run (summary.json present).
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

EVAL = Path("evaluation/job_light_imdb_non_trajectory")
CONFIGS = EVAL / "configs"
RESULTS = EVAL / "results" / "joblight_phase1" / "own_model"
SEEDS = (0, 1, 2)
TRAINING_ROOT = Path("/work_beegfs/sunip956/master_thesis_trajectories/joblight_evaluation")

WORKLOADS = {
    "job_light": {
        "rule_config": "own_model_job_light_rare_off_rule_step_11000.yaml",
        "rule_variant": "rare_off_rule_step_11000",
        "training_directory": "own_model_rare_off_40k",
    },
    "job_light_ranges": {
        "rule_config": "own_model_job_light_ranges_rare_off_rule_step_11000.yaml",
        "rule_variant": "rare_off_content_rule_step_11000",
        "training_directory": "own_model_job_light_ranges_rare_off_20k",
    },
}
RULE_STEP = 11_000
_CHECKPOINT = re.compile(r"checkpoint_step_(\d+)\.pt")


def final_variant(workload: str, seed: int) -> str:
    return f"{WORKLOADS[workload]['rule_variant'].replace('rule_step_11000', 'final')}_seed{seed}"


def final_step(run_directory: Path) -> int:
    if not (run_directory / "training_summary.json").is_file():
        raise SystemExit(f"{run_directory} has no training_summary.json (training not finished)")
    steps = [int(match.group(1)) for path in run_directory.iterdir()
             if (match := _CHECKPOINT.fullmatch(path.name))]
    if not steps:
        raise SystemExit(f"{run_directory} has no checkpoint_step_<N>.pt")
    step = max(steps)
    if step < RULE_STEP:
        raise SystemExit(f"{run_directory}: final checkpoint {step} is before the rule step {RULE_STEP}")
    return step


def final_config_text(rule_text: str, workload: str, seed: int, step: int) -> str:
    """The rule config of one seed at its final checkpoint (one level of extends kept)."""

    rule_variant = WORKLOADS[workload]["rule_variant"]
    replacements = (
        ("checkpoint_step_11000.pt", f"checkpoint_step_{step}.pt"),
        (f"variant_id: {rule_variant}", f"variant_id: {final_variant(workload, seed)}\n  seeds: [{seed}]"),
        ("display_name: Own model rule checkpoint step 11,000 (rare support off)",
         f"display_name: Own model final checkpoint step {step:,} sensitivity, training seed {seed} "
         "(rare support off)"),
    )
    text = rule_text
    for old, new in replacements:
        if old not in text:
            raise SystemExit(f"rule config lacks {old!r}")
        text = text.replace(old, new)
    header = (f"# Generated by scripts/rare_off_own_model_runs.py final-config at job start: final\n"
              f"# checkpoint {step} of training seed {seed}. Not part of final_comparison.\n")
    return header + text


def write_final_config(workload: str, seed: int, training_root: Path = TRAINING_ROOT,
                       configs: Path = CONFIGS) -> Path:
    spec = WORKLOADS[workload]
    step = final_step(training_root / spec["training_directory"] / f"seed_{seed}")
    rule_text = (configs / spec["rule_config"]).read_text(encoding="utf-8")
    path = configs / f"own_model_{workload}_rare_off_final_seed{seed}_sensitivity.yaml"
    path.write_text(final_config_text(rule_text, workload, seed, step), encoding="utf-8")
    return path


def completed_run(variant: str, seed: int, run_id: str, results: Path = RESULTS) -> Path:
    seed_directory = results / variant / f"seed_{seed}"
    matches = sorted(path for path in seed_directory.glob(f"{run_id}-*") if path.is_dir())
    if len(matches) != 1:
        raise SystemExit(f"expected one run {run_id}-* in {seed_directory}, found {len(matches)}")
    if not (matches[0] / "summary.json").is_file():
        raise SystemExit(f"{matches[0]} is not complete (no summary.json)")
    return matches[0]


def timing_plan_lines(run_id: str, results: Path = RESULTS) -> list[str]:
    lines = [f"# Rare-support-off rule rows (step 11,000), seeds 0-2; accuracy run id {run_id}."]
    for spec in WORKLOADS.values():
        for seed in SEEDS:
            run = completed_run(spec["rule_variant"], seed, run_id, results)
            lines.append(f"{CONFIGS / spec['rule_config']} {seed} {run}")
    return lines


def sensitivity_arguments(rule_run_id: str, final_run_id: str, results: Path = RESULTS) -> list[str]:
    arguments: list[str] = []
    for workload, flag in (("job_light", "job-light"), ("job_light_ranges", "ranges")):
        rule_variant = WORKLOADS[workload]["rule_variant"]
        for seed in SEEDS:
            arguments += [f"--{flag}-rule", str(completed_run(rule_variant, seed, rule_run_id, results))]
        for seed in SEEDS:
            arguments += [f"--{flag}-final",
                          str(completed_run(final_variant(workload, seed), seed, final_run_id, results))]
    return arguments


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    commands = parser.add_subparsers(dest="command", required=True)
    final = commands.add_parser("final-config")
    final.add_argument("--workload", required=True, choices=sorted(WORKLOADS))
    final.add_argument("--seed", required=True, type=int, choices=SEEDS)
    plans = commands.add_parser("timing-plans")
    plans.add_argument("--run-id", required=True)
    plans.add_argument("--output-directory", required=True, type=Path)
    sensitivity = commands.add_parser("sensitivity-args")
    sensitivity.add_argument("--rule-run-id", required=True)
    sensitivity.add_argument("--final-run-id", required=True)
    args = parser.parse_args(argv)
    if args.command == "final-config":
        print(write_final_config(args.workload, args.seed))
    elif args.command == "timing-plans":
        lines = timing_plan_lines(args.run_id)
        args.output_directory.mkdir(parents=True, exist_ok=True)
        for profile in ("cpu", "gpu"):
            path = args.output_directory / f"timing_plan_own_model_rare_off_rule_step_11000_{profile}.txt"
            path.write_text("\n".join(lines) + "\n", encoding="utf-8")
            print(path)
    else:
        print("\n".join(sensitivity_arguments(args.rule_run_id, args.final_run_id)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
